#!/usr/bin/env bash
# Stage wisedo_deploy/: the released images plus what an operator needs to
# rehearse them locally with compose. The compose file and .env.example are
# local-only (WIS-699): LOCAL-ONLY.md says what production needs instead.
# Excludes runtime state and secrets. Called by the Build and Push workflow
# with VERSION set (REGISTRY defaults to GHCR). STAGE_DIR (default wisedo_deploy, relative to
# the repository root; it must be named wisedo_deploy) lets a test stage elsewhere.
set -euo pipefail
: "${VERSION:?VERSION is required}"
REGISTRY="${REGISTRY:-ghcr.io/wisedo-technology}"
cd "$(dirname "$0")/.."
out="${STAGE_DIR:-wisedo_deploy}"
# Only ever delete a directory named wisedo_deploy: a mistyped STAGE_DIR must not erase anything else.
[ "$(basename -- "$out")" = wisedo_deploy ] || { echo "STAGE_DIR must end in /wisedo_deploy: $out" >&2; exit 1; }
rm -rf -- "$out"
mkdir -p "$out/deploy/supervisor" "$out/docs"
cp .env.example SECURITY.md "$out/"
# Every file the compose files mount, plus the optional offline-models files (WIS-708).
cp deploy/supervisor/compose.yml deploy/supervisor/bootstrap.sh deploy/supervisor/README.md \
  deploy/supervisor/model-entrypoint.sh deploy/supervisor/compose.models-runtime.yml \
  deploy/supervisor/offline-sample.png "$out/deploy/supervisor/"
cp -r docs/adr "$out/docs/"
# Pin the release. Operators copy .env.example to .env and keep this block.
cat > "$out/.env.release" <<ENV
# Generated by CI for release ${VERSION}. Append to your .env; never commit real secrets.
IMAGE_REGISTRY=${REGISTRY}
IMAGE_TAG=${VERSION}
SUPERVISOR_IMAGE=${REGISTRY}/ai-supervisor:${VERSION}
ENV
cat > "$out/LOCAL-ONLY.md" <<'DOC'
# Local rehearsal only

`.env.example` and `deploy/supervisor/compose.yml` run the release on one machine for a local
rehearsal. They are not a production deployment: they use local passwords, plain HTTP, a local
Keycloak, and a PostgreSQL and Temporal without TLS.

Production needs, and the binary refuses to boot without most of these
(`deploy/supervisor/README.md`):

- `SUPERVISOR_ENVIRONMENT=production` (the default when unset).
- `SUPERVISOR_DATABASE_URL`, `SUPERVISOR_MIGRATION_URL` and `SUPERVISOR_PROVISIONING_URL` with
  `sslmode=verify-full` (or `verify-ca`) and the CA bundle.
- `SUPERVISOR_TEMPORAL_TLS=true`.
- HTTPS for `SUPERVISOR_PUBLIC_ORIGIN` and `SUPERVISOR_OIDC_ISSUER`, with your own identity
  provider.
- A real model provider (`SUPERVISOR_AGENT_PROVIDER=local` pinned to your endpoint); the
  deterministic fixture provider is refused in production.
- Secrets from your secret store, never from a committed `.env`.
DOC
# The two local-only files must say so where an operator first looks (WIS-699).
for f in "$out/.env.example" "$out/deploy/supervisor/compose.yml"; do
  head -n 1 "$f" | grep -q '^# LOCAL REHEARSAL ONLY' || { echo "$f lost its LOCAL REHEARSAL ONLY marker" >&2; exit 1; }
done
printf '%s\n' "$VERSION" > "$out/VERSION"
find "$out" -type f | sort
