//go:build ignore

// core14_gen writes core14_widths.go: the widths, glyph names and font boxes of the 14 standard
// PDF fonts from Adobe's Core14 AFM files, and the WinAnsiEncoding glyph names, as shipped in the
// pdfcpu module this repository already pins, and the Unicode value of each of those glyph names
// from the glyph-name table of the pinned ledongthuc/pdf module (the extractor's own). Run from
// internal/onboarding:
//
//	go run core14_gen.go "$(go list -m -f '{{.Dir}}' github.com/pdfcpu/pdfcpu)" "$(go list -m -f '{{.Dir}}' github.com/ledongthuc/pdf)"
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

var fonts = []string{"Courier", "Courier-Bold", "Courier-BoldOblique", "Courier-Oblique", "Helvetica", "Helvetica-Bold", "Helvetica-BoldOblique",
	"Helvetica-Oblique", "Symbol", "Times-Bold", "Times-BoldItalic", "Times-Italic", "Times-Roman", "ZapfDingbats"}

func main() {
	dir, ldir := os.Args[1], os.Args[2]
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by core14_gen.go from the Adobe Core14 AFM files in %s and the glyph names of %s; DO NOT EDIT.\n//\n// Sources (SHA-256):\n",
		"github.com/pdfcpu/pdfcpu@v0.11.0", "github.com/ledongthuc/pdf@v0.0.0-20261020125853-5e46805f718e")
	sum := func(rel string) []byte {
		root := dir
		if strings.HasPrefix(rel, "name.go") {
			root = ldir
		}
		b, err := os.ReadFile(filepath.Join(root, rel))
		if err != nil {
			panic(err)
		}
		fmt.Fprintf(&out, "//   %x  %s\n", sha256.Sum256(b), rel)
		return b
	}
	type font struct {
		bbox    [4]int
		asc     int
		desc    int
		widths  map[string]int
		boxes   map[string][4]int
		builtin map[int]string
	}
	parsed := map[string]font{}
	for _, name := range fonts {
		b := sum("internal/corefont/Core14_AFMs/" + name + ".afm")
		f := font{widths: map[string]int{}, boxes: map[string][4]int{}, builtin: map[int]string{}}
		sc := bufio.NewScanner(bytes.NewReader(b))
		for sc.Scan() {
			line := sc.Text()
			if fs := strings.Fields(line); len(fs) == 2 && fs[0] == "Ascender" {
				f.asc, _ = strconv.Atoi(fs[1])
			} else if len(fs) == 2 && fs[0] == "Descender" {
				f.desc, _ = strconv.Atoi(fs[1])
			}
			if strings.HasPrefix(line, "FontBBox ") {
				fs := strings.Fields(line)
				for i := range f.bbox {
					f.bbox[i], _ = strconv.Atoi(fs[i+1])
				}
			}
			if !strings.HasPrefix(line, "C ") {
				continue
			}
			var code, w int
			var glyph string
			var bb [4]int
			for _, part := range strings.Split(line, ";") {
				fs := strings.Fields(part)
				if len(fs) < 2 {
					continue
				}
				switch fs[0] {
				case "C":
					code, _ = strconv.Atoi(fs[1])
				case "WX":
					w, _ = strconv.Atoi(fs[1])
				case "N":
					glyph = fs[1]
				case "B":
					for k := 0; k < 4 && k+1 < len(fs); k++ {
						bb[k], _ = strconv.Atoi(fs[k+1])
					}
				}
			}
			f.widths[glyph] = w
			f.boxes[glyph] = bb
			if code >= 0 {
				f.builtin[code] = glyph
			}
		}
		parsed[name] = f
	}
	std := sum("internal/corefont/metrics/standard.go")
	ln := string(sum("name.go"))
	block := string(std)
	block = block[strings.Index(block, "var WinAnsiGlyphMap"):]
	block = block[:strings.Index(block, "\n}")]
	win := map[int]string{}
	for _, m := range regexp.MustCompile(`(?m)^\s*(\d+):\s*"([^"]+)"`).FindAllStringSubmatch(block, -1) {
		c, _ := strconv.Atoi(m[1])
		win[c] = m[2]
	}
	out.WriteString("\npackage onboarding\n\n")
	out.WriteString("// core14Fonts are the 14 standard fonts: font box, built-in encoding and glyph widths (1/1000 em).\nvar core14Fonts = map[string]core14Font{\n")
	for _, name := range fonts {
		f := parsed[name]
		fmt.Fprintf(&out, "%q: {bbox: [4]float64{%d, %d, %d, %d}, ascent: %d, descent: %d,\nbuiltin: map[int]string{", name, f.bbox[0], f.bbox[1], f.bbox[2], f.bbox[3], f.asc, f.desc)
		codes := make([]int, 0, len(f.builtin))
		for c := range f.builtin {
			codes = append(codes, c)
		}
		sort.Ints(codes)
		for i, c := range codes {
			if i%8 == 0 {
				out.WriteString("\n")
			}
			fmt.Fprintf(&out, "%d: %q, ", c, f.builtin[c])
		}
		out.WriteString("\n},\nwidths: map[string]float64{")
		names := make([]string, 0, len(f.widths))
		for n := range f.widths {
			names = append(names, n)
		}
		sort.Strings(names)
		for i, n := range names {
			if i%8 == 0 {
				out.WriteString("\n")
			}
			fmt.Fprintf(&out, "%q: %d, ", n, f.widths[n])
		}
		out.WriteString("\n},\nboxes: map[string][4]float64{")
		for i, n := range names {
			if i%4 == 0 {
				out.WriteString("\n")
			}
			b := f.boxes[n]
			fmt.Fprintf(&out, "%q: {%d, %d, %d, %d}, ", n, b[0], b[1], b[2], b[3])
		}
		out.WriteString("\n}},\n")
	}
	out.WriteString("}\n\n// winAnsiNames are WinAnsiEncoding's glyph names by code.\nvar winAnsiNames = map[int]string{")
	codes := make([]int, 0, len(win))
	for c := range win {
		codes = append(codes, c)
	}
	sort.Ints(codes)
	for i, c := range codes {
		if i%8 == 0 {
			out.WriteString("\n")
		}
		fmt.Fprintf(&out, "%d: %q, ", c, win[c])
	}
	out.WriteString("\n}\n")
	// The Unicode value of every glyph name above, as the extractor maps it.
	runes := map[string]string{}
	for _, m := range regexp.MustCompile(`(?m)^\s*"([^"]+)":\s*(0x[0-9A-Fa-f]+),`).FindAllStringSubmatch(ln, -1) {
		if _, dup := runes[m[1]]; !dup {
			runes[m[1]] = m[2]
		}
	}
	used := map[string]bool{}
	for _, f := range parsed {
		for n := range f.widths {
			used[n] = true
		}
	}
	for _, n := range win {
		used[n] = true
	}
	names := make([]string, 0, len(used))
	for n := range used {
		if _, ok := runes[n]; ok {
			names = append(names, n)
		}
	}
	sort.Strings(names)
	out.WriteString("\n// glyphRunes are the Unicode values of the glyph names above (none for ZapfDingbats' a1...).\nvar glyphRunes = map[string]rune{")
	for i, n := range names {
		if i%6 == 0 {
			out.WriteString("\n")
		}
		fmt.Fprintf(&out, "%q: %s, ", n, runes[n])
	}
	out.WriteString("\n}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		panic(err)
	}
	if err := os.WriteFile("core14_widths.go", src, 0o644); err != nil {
		panic(err)
	}
}
