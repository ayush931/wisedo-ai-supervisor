//go:build ignore

// confusables_gen.go generates confusables_table.go from the Unicode UTS #39 confusables data,
// pinned to one Unicode version by URL and SHA-256 (WIS-623). Run with `go generate ./internal/agent`
// (network) or `go run confusables_gen.go -file confusables.txt` with a local copy of the same file.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
	"strings"
)

const (
	version = "16.0.0"
	source  = "https://www.unicode.org/Public/security/" + version + "/confusables.txt"
	digest  = "95bd0aad6dced5ebc63436f459c06ab21a8d107cd842fb57f5c3a1e91bca8611"
)

func main() {
	file := flag.String("file", "", "local copy of "+source+" (default: download)")
	flag.Parse()
	var data []byte
	var err error
	if *file != "" {
		data, err = os.ReadFile(*file)
	} else {
		var res *http.Response
		if res, err = http.Get(source); err == nil {
			defer res.Body.Close()
			if res.StatusCode != http.StatusOK {
				log.Fatalf("%s: HTTP %d", source, res.StatusCode)
			}
			data, err = io.ReadAll(res.Body)
		}
	}
	if err != nil {
		log.Fatal(err)
	}
	if sum := sha256.Sum256(data); hex.EncodeToString(sum[:]) != digest {
		log.Fatalf("confusables.txt SHA-256 %x, want %s", sum, digest)
	}
	// Each data line: source ; target sequence ; type # comment. Only non-ASCII sources are kept:
	// ASCII text is matched as written (after case folding), so "m" never reads as "rn" and digits
	// stay digits for the phone and number rules.
	table := map[rune]string{}
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		fields := strings.Split(line, ";")
		if len(fields) < 3 {
			continue
		}
		src, err := strconv.ParseUint(strings.TrimSpace(fields[0]), 16, 32)
		if err != nil {
			log.Fatalf("source %q: %v", fields[0], err)
		}
		if src < 0x80 {
			continue
		}
		var target strings.Builder
		for _, cp := range strings.Fields(fields[1]) {
			r, err := strconv.ParseUint(cp, 16, 32)
			if err != nil {
				log.Fatalf("target %q: %v", fields[1], err)
			}
			target.WriteRune(rune(r))
		}
		table[rune(src)] = target.String()
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	keys := make([]rune, 0, len(table))
	for r := range table {
		keys = append(keys, r)
	}
	sort.Slice(keys, func(i, j int) bool { return keys[i] < keys[j] })
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by confusables_gen.go; DO NOT EDIT.\n\n")
	fmt.Fprintf(&out, "// Source: %s\n// Unicode version: %s\n// SHA-256: %s\n\n", source, version, digest)
	fmt.Fprintf(&out, "package agent\n\n")
	fmt.Fprintf(&out, "// confusablesVersion is the Unicode version of the UTS #39 data in confusables.\nconst confusablesVersion = %q\n\n", version)
	fmt.Fprintf(&out, "// confusables maps each non-ASCII source code point of UTS #39 confusables.txt to its\n// prototype (%d entries).\nvar confusables = map[rune]string{\n", len(keys))
	for _, r := range keys {
		fmt.Fprintf(&out, "\t0x%04X: %q,\n", r, table[r])
	}
	fmt.Fprintf(&out, "}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("confusables_table.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
