//go:build ignore

// entities_gen.go generates entities_table.go: the names of the HTML character references the
// Go standard library decodes (html.UnescapeString), read from the html package of the Go
// toolchain that runs it (WIS-623 Codex round 32: the audit matches entity names over reading
// sets, so it needs the names; the values still come from html.UnescapeString). Run with
// `go generate ./internal/agent`.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"runtime"
	"sort"
)

func main() {
	src, err := os.ReadFile(filepath.Join(runtime.GOROOT(), "src", "html", "entity.go"))
	if err != nil {
		log.Fatal(err)
	}
	seen := map[string]bool{}
	var names []string
	for _, m := range regexp.MustCompile(`(?m)^\t\t"([A-Za-z0-9]+;?)":`).FindAllSubmatch(src, -1) {
		if n := string(m[1]); !seen[n] {
			seen[n] = true
			names = append(names, n)
		}
	}
	if len(names) < 2000 {
		log.Fatalf("only %d entity names found: the html package layout changed", len(names))
	}
	sort.Strings(names)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by entities_gen.go; DO NOT EDIT.\n\n// Source: the html package of %s.\n\npackage agent\n\n", runtime.Version())
	fmt.Fprintf(&b, "// htmlEntityNames are the character reference names html.UnescapeString decodes (%d).\nvar htmlEntityNames = []string{\n", len(names))
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q,\n", n)
	}
	b.WriteString("}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("entities_table.go", out, 0o644); err != nil {
		log.Fatal(err)
	}
}
