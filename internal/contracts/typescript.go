package contracts

import (
	"fmt"
	"sort"
	"strings"
)

// typeScript renders the published schemas as TypeScript declarations for web consumers
// (WIS-229 generated-consumer compatibility). It reads the same closed schemas the OpenAPI
// document embeds, so a consumer type can never drift from the provider contract. Arrays are
// readonly so recorded provider responses typecheck as `as const` literals.
func typeScript(schemas map[string]any) []byte {
	names := make([]string, 0, len(schemas))
	for name := range schemas {
		names = append(names, name)
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString("// Generated by cmd/supervisor-contracts from the published JSON Schemas. Do not edit.\n")
	for _, name := range names {
		fmt.Fprintf(&b, "\nexport type %s = %s;\n", name, tsType(schemas[name].(map[string]any), 0))
	}
	return []byte(b.String())
}

func tsType(s map[string]any, depth int) string {
	if alts, ok := s["anyOf"].([]any); ok {
		parts := make([]string, len(alts))
		for i, a := range alts {
			parts[i] = tsType(a.(map[string]any), depth)
		}
		return strings.Join(parts, " | ")
	}
	if values, ok := s["enum"].([]any); ok {
		parts := make([]string, len(values))
		for i, v := range values {
			parts[i] = fmt.Sprintf("%q", v)
		}
		return strings.Join(parts, " | ")
	}
	switch s["type"] {
	case "string":
		return "string"
	case "integer":
		return "number"
	case "boolean":
		return "boolean"
	case "null":
		return "null"
	case "array":
		return "readonly (" + tsType(s["items"].(map[string]any), depth) + ")[]"
	case nil:
		return "unknown"
	case "object":
		props, _ := s["properties"].(map[string]any)
		required := map[string]bool{}
		for _, r := range s["required"].([]any) {
			required[r.(string)] = true
		}
		keys := make([]string, 0, len(props))
		for k := range props {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		indent := strings.Repeat("  ", depth+1)
		var b strings.Builder
		b.WriteString("{\n")
		for _, k := range keys {
			optional := ""
			if !required[k] {
				optional = "?"
			}
			fmt.Fprintf(&b, "%s%s%s: %s;\n", indent, k, optional, tsType(props[k].(map[string]any), depth+1))
		}
		b.WriteString(strings.Repeat("  ", depth) + "}")
		return b.String()
	}
	panic(fmt.Sprintf("contracts: no TypeScript mapping for schema %v", s))
}
